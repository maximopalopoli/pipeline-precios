-- seed_producto_tipos.sql
-- Product type dictionary (migration 040). This file is the source of truth:
-- every migration run replaces producto_tipo_terminos with these rows, so edit
-- here, never in the database. A change reaches dim_producto.tipo with the next
-- full ingestion.
--
-- A term is one to three words as pipeline_normalize_text writes them: upper
-- case, no accents, Ñ as N, other characters as spaces ("ALIM.P/GATOS" is
-- "ALIM P GATOS"). A description takes the type of the term at its first
-- word, the longest one when several start there. Set tras_marca only for a
-- term that never names an ingredient or flavor (SH, DEO, YOG): it also
-- matches at the second or third word, behind a brand ("SEDAL SH ...").
-- LECHE, CHOCOLATE or AGUA must not: "ALFAJOR ... LECHE", "PISTOLA DE AGUA".
--
-- Add a term only when it names one kind of product. Leave out words that
-- name several: TAB (tablet or chocolate bar), P (papel or plato), DES
-- (deodorant or disinfectant), CREMA, GEL, BARRA, JUEGO, SET, KIT.
-- A longer phrase can still type them: CREMA DENTAL, GEL FIJADOR.

